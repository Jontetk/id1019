defmodule Color do
  def convert(depth,max) do
    convert_rain(depth,max)
  end

  def convert_gray(depth,max) do
    gray = trunc((depth/max)*255)
    {:rgb,gray,gray,gray}
  end
  def convert_blue(depth,max) do
    blue = trunc((depth/max)*255)
    {:rgb,0,0,blue}
  end
  def convert_bluered(depth,max) do
    color = trunc((depth/max)*255)
    {:rgb,color,0,color}
  end
  def convert_rain(depth,max) do
    color = trunc((depth/max)*255)
    case(div(color,51)) do
      0 -> {:rgb,color,0,0}
      1->{:rgb,color,color,0}
      2->{:rgb,0,color,0}
      3->{:rgb,0,color,color}
      4->{:rgb,0,0,color}
      5->{:rgb,color,0,color}
      6->{:rgb,color,color,color}
    end
  end

end

defmodule Mandel do



  def process_creator(_,_,_,_,_,_,_,proc_num,0,processes) do
    {processes,proc_num}
  end

  def process_creator(width,height,trans,depth,ctrl,x,y,proc_num,num,processes) do
    case x == width do
      true -> process_creator(width,height,trans,depth,ctrl,0,y+1,proc_num,num,processes)
      false -> case y==height do
        true -> processes
        false -> process_creator(width,height,trans,depth,ctrl,x+1,y,proc_num+1,num-1,[spawn(fn () -> mandel_calc(width,height,trans,depth,ctrl,x,y,proc_num) end)|processes])
      end
    end
  end


  def mandelbrot(width, height, x, y, k, depth) do
    trans = fn(w, h) ->
      Cmplx.new(x + k * (w - 1), y - k * (h - 1))
    end
    row_spawner(width, height, trans, depth,[])
  end

  def row_spawner(width,height,trans,depth,list) do
    ctrl = self()
    {processes,proc_num}=process_creator(width,height,trans,depth,ctrl,0,0,0,32,[])
    list = rows(width,height,trans,depth,list,0,0,proc_num,0)
    Enum.map(processes,fn process -> send(process,:quit)  end)
    list
  end
  def rows(width,height,trans,depth,[hlist|tlist],x,y,proc_num,wait_num) do
    receive do
      {:mand_done,^wait_num,res,proc} ->
        {x,y,[hlist|tlist]} = case x== width do
          true -> {0,y+1,[[]|[hlist|tlist]]}
          false -> {x,y,[hlist|tlist]}
        end
        case y == height do
          true -> tlist
          false -> send(proc,{:new_calc,x,y,proc_num}); rows(width,height,trans,depth,[hlist++[res]|tlist],x+1,y,proc_num+1,wait_num+1)
        end


    end

  end
  def rows(width,height,trans,depth,[],x,y,proc_num,wait_num) do
    receive do
      {:mand_done,^wait_num,res,proc} ->
        {x,y,list} = case x== width do
          true -> {0,y+1,[[]|[]]}
          false -> {x,y,[]}
        end
        case y == height do
          true -> list
          false -> send(proc,{:new_calc,x,y,proc_num}); rows(width,height,trans,depth,[[res]],x+1,y,proc_num+1,wait_num+1)
        end


    end

  end
  def mandel_calc(width,height,trans,depth,ctrl,x,y,proc_num) do
    case x == width do
      true -> mandel_calc(width,height,trans,depth,ctrl,0,y+1,proc_num)
      false -> case y==height do
        false -> mandel_calc_go(width,height,trans,depth,ctrl,x,y,proc_num)
        true -> :error
      end
      end
  end
  def mandel_calc_go(width,height,trans,depth,ctrl,x,y,proc_num) do



    res = Color.convert(Brot.mandelbrot(trans.(x,y),depth),depth)
    self = self()
    send(ctrl,{:mand_done,proc_num,res,self})
    receive do
      {:new_calc,new_x,new_y,new_proc_num} -> mandel_calc(width,height,trans,depth,ctrl,new_x,new_y,new_proc_num)
      {:quit} -> :ok
    end

  end


  def demo() do
    :timer.tc(fn()->small(-2.6,2.5, 2.5)end)
    end
    def small(x0, y0, xn) do
      width = 500
      height = 500
    depth = 50
    k = (xn - x0) / width
    image = Mandel.mandelbrot(width, height, x0, y0, k, depth)
    PPM.write("small.ppm", image)
    end

end
