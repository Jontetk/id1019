defmodule Color do
  def convert(depth,max) do
    convert_bluered(depth,max)
  end

  def convert_gray(depth,max) do
    gray = trunc((depth/max)*255)
    {:rgb,gray,gray,gray}
  end
  def convert_blue(depth,max) do
    blue = trunc((depth/max)*255)
    {:rgb,0,0,blue}
  end
  def convert_bluered(depth,max) do
    color = trunc((depth/max)*255)
    {:rgb,color,0,color}
  end


end

defmodule Mandel do
  def mandelbrot(width, height, x, y, k, depth) do
    trans = fn(w, h) ->
      Cmplx.new(x + k * (w - 1), y - k * (h - 1))
    end
    rows(width, height, trans, depth, [[Color.convert(Brot.mandelbrot(trans.(0,0),depth),depth)]],1,0)
  end


  def rows(width,height,trans,depth,[hlist|tlist],x,y) do
    case x == width do
      true ->rows(width,height,trans,depth,[[]|[hlist|tlist]],0,y+1)
      false-> case y == height do
         true->[hlist|tlist]
          false-> rows(width,height,trans,depth,[hlist++[Color.convert(Brot.mandelbrot(trans.(x,y),depth),depth)]|tlist],x+1,y)
      end
    end
  end
