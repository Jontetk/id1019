defmodule Color do
  def convert(depth,max) do
    convert_gray(depth,max)
  end

  def convert_gray(depth,max) do
    gray = trunc((depth/max)*255)
    {:rgb,gray,gray,gray}
  end
  def convert_blue(depth,max) do
    blue = trunc((depth/max)*255)
    {:rgb,0,0,blue}
  end
  def convert_bluered(depth,max) do
    color = trunc((depth/max)*255)
    {:rgb,color,0,color}
  end
  def convert_rain(depth,max) do
    color = trunc((depth/max)*255)
    case(div(color,51)) do
      0 -> {:rgb,color,0,0}
      1->{:rgb,color,color,0}
      2->{:rgb,0,color,0}
      3->{:rgb,0,color,color}
      4->{:rgb,0,0,color}
      5->{:rgb,color,0,color}
      6->{:rgb,color,color,color}
    end
  end
  def convert_suggested(d,m) do

    a = (d/m)*4
    x = trunc(a)
    y=trunc(255*(a-x))
    case x do
      0 -> {:rgb,y, 0, 0}
      1 -> {:rgb,255, y, 0}
      2 -> {:rgb,255 - y, 255, 0}
      3 -> {:rgb,0, 255, y}
      4 -> {:rgb,0, 255 - y, 255}
    end
  end

end
